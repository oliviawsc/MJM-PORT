-- =====================================================================
-- Estate Info: tables you design yourself (Estate Info → Settings)
--
--   port_estate_tables   one row per table: its name and its columns
--                        (columns = [{ key, label, type, options, required }],
--                        type = text | number | date | yesno | choice).
--                        per_estate = records kept per location of a company
--                        (e.g. Mega Jutamas → Sg Rait / Suai / Ulu Niah);
--                        otherwise one set of records per company.
--   port_estate_records  the rows people fill in: table, Intranet company,
--                        location (estate, '' when per company) and the values
--                        by column key.
--
-- Also: port_ffb_penalty and the new tables get company_id (Intranet company
-- id) like every other data table, and the old-estate → company list can be
-- read by the pages (names only).
-- Safe to run more than once.
-- =====================================================================

create table if not exists public.port_estate_tables (
  id           bigint generated by default as identity primary key,
  name         text not null check (char_length(name) between 1 and 80),
  description  text not null default '',
  columns      jsonb not null default '[]'::jsonb check (jsonb_typeof(columns) = 'array'),
  per_estate   boolean not null default false,
  sort_order   integer not null default 0,
  is_active    boolean not null default true,
  created_by   text not null default '',
  updated_by   text not null default '',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists public.port_estate_records (
  id          bigint generated by default as identity primary key,
  table_id    bigint not null references public.port_estate_tables (id) on delete cascade,
  company_id  uuid references public.port_companies (id),
  estate      text not null default '',          -- location; '' when the table is per company
  data        jsonb not null default '{}'::jsonb check (jsonb_typeof(data) = 'object'),
  sort_order  integer not null default 0,
  updated_by  text not null default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists port_estate_records_table_company_idx on public.port_estate_records (table_id, company_id, estate);

-- company_id on the blocks and the FFB penalty table too (filled from the estate name)
do $$
declare t text;
begin
  foreach t in array array['port_estate_blocks', 'port_ffb_penalty'] loop
    if to_regclass('public.' || t) is null then continue; end if;
    execute format('alter table public.%I add column if not exists company_id uuid references public.port_companies (id)', t);
    execute format('create index if not exists %I on public.%I (company_id)', t || '_company_idx', t);
    execute format('drop trigger if exists port_fill_company_id on public.%I', t);
    execute format('create trigger port_fill_company_id before insert or update of estate, company_id on public.%I '
                   'for each row execute function public.port_fill_company_id()', t);
    execute format('update public.%I d set company_id = m.company_id from public.port_estate_company m
                     where d.company_id is null and m.company_id is not null and d.estate = m.estate', t);
  end loop;
end $$;

-- Same access as the other port_* tables until the cutover rules
do $$
declare t text;
begin
  foreach t in array array['port_estate_tables', 'port_estate_records'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('grant select, insert, update, delete on public.%I to anon, authenticated', t);
    execute format('drop policy if exists %I on public.%I', t || '_all', t);
    execute format('create policy %I on public.%I for all to anon, authenticated using (true) with check (true)', t || '_all', t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to anon, authenticated;

-- The pages read which locations (old estate names) belong to a company
grant select on public.port_estate_company to anon, authenticated;
drop policy if exists port_estate_company_read on public.port_estate_company;
create policy port_estate_company_read on public.port_estate_company for select to anon, authenticated using (true);
