-- Estate Info module: the blocks of each estate.
--   estate   = port_estates.name (the company itself for a single-estate company)
--   division / phase are optional levels above the block; an estate without them
--   leaves both empty and the module shows the Block column only.
create table if not exists public.port_estate_blocks (
  id            bigint generated by default as identity primary key,
  estate        text not null,
  division      text not null default '',
  phase         text not null default '',
  block         text not null,
  area_ha       numeric(10,2),
  palm_count    integer,
  density       numeric(8,2),           -- palms per ha; left empty = palm_count / area_ha
  year_planted  integer,
  remark        text not null default '',
  sort_order    integer not null default 0,
  updated_by    text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (estate, division, phase, block)
);
create index if not exists port_estate_blocks_estate_idx on public.port_estate_blocks (estate);

alter table public.port_estate_blocks enable row level security;
grant select, insert, update, delete on public.port_estate_blocks to anon, authenticated;
drop policy if exists port_estate_blocks_all on public.port_estate_blocks;
create policy port_estate_blocks_all on public.port_estate_blocks for all to anon, authenticated using (true) with check (true);
grant usage, select on all sequences in schema public to anon, authenticated;
